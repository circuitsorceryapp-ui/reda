// Company logo & profile tests — run against a live server: node test-logo.js http://localhost:PORT
const BASE = process.argv[2] || 'http://localhost:3222';
let pass=0, fail=0; const ok=(l,c,e='')=>{c?pass++:(fail++,console.log('FAIL',l,e||''));};
const PNG='iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mP8z8BQDwAEhQGAhKmMIQAAAABJRU5ErkJggg==';
const mk=()=>{ const jar={v:''}; const api=async(m,p,b,raw)=>{ const r=await fetch(BASE+p,{method:m,headers:{'Content-Type':'application/json',...(jar.v?{Cookie:jar.v}:{})},body:b?JSON.stringify(b):undefined}); const sc=r.headers.get('set-cookie'); if(sc)jar.v=sc.split(';')[0]; if(raw)return r; let d=null; try{d=await r.json()}catch{}; return{s:r.status,d}; }; return {api}; };
(async()=>{
  const O=mk();
  let r=await O.api('POST','/api/register',{companyName:'LogoCo',name:'L',email:`l${Date.now()}@t.lv`,password:'password123'});
  ok('register',r.d.ok===true);
  r=await O.api('GET','/api/company');
  ok('empty profile defaults',r.d.company==='LogoCo'&&r.d.has_logo===false&&r.d.address==='');
  r=await O.api('POST','/api/company',{address:'Bērzu 1, Rīga',reg_no:'40123456789',vat_no:'LV40123456789',bank:'LV12BANK',phone:'+3712',email:'info@l.lv'});
  ok('save profile',r.d.ok===true);
  r=await O.api('GET','/api/company');
  ok('profile round-trip',r.d.address==='Bērzu 1, Rīga'&&r.d.vat_no==='LV40123456789'&&r.d.bank==='LV12BANK');
  r=await O.api('POST','/api/company/logo',{data:'data:image/png;base64,'+PNG});
  ok('upload logo',r.d.ok===true,JSON.stringify(r.d));
  r=await O.api('POST','/api/company/logo',{data:'not-an-image'});
  ok('bad logo rejected',!!r.d.error);
  r=await O.api('POST','/api/company/logo',{data:'data:image/png;base64,'+'A'.repeat(700000)});
  ok('oversize logo rejected',!!r.d.error);
  const img=await O.api('GET','/api/company/logo',null,true);
  ok('logo served as png',img.status===200&&img.headers.get('content-type')==='image/png');
  const buf=Buffer.from(await img.arrayBuffer());
  ok('logo bytes intact',buf.equals(Buffer.from(PNG,'base64')));
  const na=await fetch(BASE+'/api/company/logo');
  ok('logo requires login',na.status===401);
  const E=mk();
  await E.api('POST','/api/register',{companyName:'Other',name:'O',email:`o${Date.now()}@t.lv`,password:'password123'});
  const img2=await E.api('GET','/api/company/logo',null,true);
  ok('other tenant has no logo',img2.status===404);
  r=await E.api('GET','/api/company');
  ok('other tenant profile empty',r.d.address===''&&r.d.company==='Other');
  r=await O.api('DELETE','/api/company/logo');
  ok('remove logo',r.d.ok===true);
  const img3=await O.api('GET','/api/company/logo',null,true);
  ok('logo gone after delete',img3.status===404);
  r=await O.api('GET','/api/company');
  ok('details survive logo delete',r.d.address==='Bērzu 1, Rīga'&&r.d.has_logo===false);
  console.log(`\nlogo/profile tests: ${pass} passed, ${fail} failed`);
  process.exit(fail?1:0);
})().catch(e=>{console.error('CRASH',e);process.exit(2)});
